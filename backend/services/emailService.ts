import nodemailer, { type Transporter } from "nodemailer";
import type { AlertEvent } from "@prisma/client";

let transporter: Transporter | undefined;

function getTransporter(): Transporter {
  if (transporter) return transporter;

  const host = process.env.SMTP_HOST;
  const port = Number(process.env.SMTP_PORT);
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;
  const from = process.env.EMAIL_FROM;

  if (!host || !Number.isInteger(port) || port < 1 || port > 65535 || !user || !pass || !from) {
    throw new Error("Email delivery is not configured. Set SMTP_HOST, SMTP_PORT, SMTP_USER, SMTP_PASS, and EMAIL_FROM.");
  }

  transporter = nodemailer.createTransport({
    host,
    port,
    secure: process.env.SMTP_SECURE === "true",
    auth: { user, pass },
    connectionTimeout: 5_000,
    greetingTimeout: 5_000,
    socketTimeout: 10_000,
  });
  return transporter;
}

export async function verifyEmailTransport(): Promise<void> {
  await getTransporter().verify();
}

export async function sendMonitorAlert(input: {
  to: string;
  projectName: string;
  projectUrl: string;
  event: AlertEvent;
  checkedAt: Date;
  status: number | null;
  responseTime: number | null;
}): Promise<void> {
  const isDown = input.event === "DOWN";
  const isCreated = input.event === "CREATED";
  const label = isDown ? "is not responding" : isCreated ? "is now being monitored" : "has recovered";
  const from = process.env.EMAIL_FROM;

  await getTransporter().sendMail({
    from,
    to: input.to,
    subject: `${isDown ? "Monitor alert" : isCreated ? "Monitoring started" : "Monitor recovered"}: ${input.projectName}`,
    text: [
      `Your monitor for ${input.projectName} ${label}.`,
      `Endpoint: ${input.projectUrl}`,
      `Checked at: ${input.checkedAt.toISOString()}`,
      ...(input.status === null ? [] : [`HTTP status: ${input.status}`]),
      ...(input.responseTime === null ? [] : [`Response time: ${input.responseTime} ms`]),
      "",
      "This notification was generated by your WTFup monitor.",
    ].join("\n"),
  });
}
